#!/usr/bin/env node
// build_remap.mjs - generates the two lists read by the URL remap (ART_VOXEL_PSX.md section 4.2).
//
//   <out-dir>/voxelIndex.ts    VOXEL_INDEX   Set of every converted voxel model that exists under
//                                            public/assets/models/voxel/ (the resolver falls back per file)
//   <out-dir>/voxelReplace.ts  VOXEL_REPLACE source URL -> voxel URL, from tools/voxel/replace.json
//                                            (written by build_replace.py in WP5; absent = empty map)
//
// usage (repo root):  node tools/voxel/build_remap.mjs [--out-dir src/core] [--replace tools/voxel/replace.json] [--check]
//   --check   write nothing; exit 1 if the generated files are out of date.
// Files are only rewritten when their content changes, so a no-op run does not touch Vite's module graph.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..', '..');
const args = process.argv.slice(2);
const opt = (name, def) => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] !== undefined ? args[i + 1] : def;
};
const outDir = path.resolve(REPO, opt('--out-dir', 'src/core'));
const replacePath = path.resolve(REPO, opt('--replace', 'tools/voxel/replace.json'));
const check = args.includes('--check');

const URL_ROOT = '/assets/models/voxel/';
const SRC_PREFIX = '/assets/models/';
const voxelRoot = path.resolve(REPO, 'public', 'assets', 'models', 'voxel');

function walkGlb(dir) {
  const found = [];
  if (!fs.existsSync(dir)) return found;
  for (const de of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, de.name);
    if (de.isDirectory()) found.push(...walkGlb(p));
    else if (de.isFile() && /\.glb$/i.test(de.name)) found.push(p);
  }
  return found;
}

const indexUrls = walkGlb(voxelRoot)
  .map((p) => URL_ROOT + path.relative(voxelRoot, p).split(path.sep).join('/'))
  .sort();
const indexSet = new Set(indexUrls);

const warnings = [];
let replaceIn = {};
if (fs.existsSync(replacePath)) {
  try {
    replaceIn = JSON.parse(fs.readFileSync(replacePath, 'utf8'));
  } catch (e) {
    console.error(`build_remap: cannot parse ${replacePath}: ${e.message}`);
    process.exit(1);
  }
}
const replace = {};
for (const src of Object.keys(replaceIn).sort()) {
  const dst = replaceIn[src];
  if (!src.startsWith(SRC_PREFIX)) warnings.push(`source key outside ${SRC_PREFIX}: ${src}`);
  if (typeof dst !== 'string' || !indexSet.has(dst)) {
    warnings.push(`replacement missing on disk, not emitted: ${src} -> ${dst}`);
    continue;
  }
  replace[src] = dst;
}

const banner = (what) =>
  `// GENERATED by tools/voxel/build_remap.mjs from public/assets/models/voxel (do not edit by hand).\n// ${what}\n`;

const indexTs =
  banner(`${indexUrls.length} converted voxel models.`) +
  `export const VOXEL_INDEX: ReadonlySet<string> = new Set<string>([\n` +
  indexUrls.map((u) => `  ${JSON.stringify(u)},`).join('\n') +
  (indexUrls.length ? '\n' : '') +
  `]);\n`;

const replaceTs =
  banner(`${Object.keys(replace).length} source-to-voxel replacements (tools/voxel/replace.json).`) +
  `export const VOXEL_REPLACE: Readonly<Record<string, string>> = {\n` +
  Object.keys(replace).map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(replace[k])},`).join('\n') +
  (Object.keys(replace).length ? '\n' : '') +
  `};\n`;

const targets = [
  [path.join(outDir, 'voxelIndex.ts'), indexTs],
  [path.join(outDir, 'voxelReplace.ts'), replaceTs],
];

let stale = false;
for (const [file, body] of targets) {
  const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (cur === body) continue;
  stale = true;
  if (check) {
    console.log(`stale: ${path.relative(REPO, file)}`);
    continue;
  }
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(file, body, 'utf8');
  console.log(`wrote ${path.relative(REPO, file)}`);
}
if (!stale) console.log('remap lists up to date');
console.log(`voxel models: ${indexUrls.length}, replacements: ${Object.keys(replace).length}`);
for (const w of warnings) console.log(`warning: ${w}`);
process.exit(check && stale ? 1 : 0);
